package com.tka;

public class ComparisionOperators {

	public static void main(String args[]) {
		
		int a = 10;
		int b = 7;
		
		System.out.println(a+" == "+b+" : "+(a==b));
		System.out.println(a+" != "+b+" : "+(a!=b));
		System.out.println(a+" < "+b+" : "+(a<b));
		System.out.println(a+" > "+b+" : "+(a>b));
		System.out.println(a+" <= "+b+" : "+(a<=b));
		System.out.println(a+" >= "+b+" : "+(a>=b));
	}
}
